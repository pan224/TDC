`timescale 1ns / 1ps

module tb_tdc_test_ctrl_phase;

//==============================================================================
// 参数定义
//==============================================================================
parameter DATA_WIDTH = 8;
parameter CLK_PERIOD = 5;  // 200MHz 时钟周期 = 5ns

//==============================================================================
// 信号声明
//==============================================================================
// 时钟和复位
reg clk_sys;
reg vio_reset_in;

// VIO 控制信号
reg [DATA_WIDTH-1:0] vio_phase;
reg vio_valid;
reg sel_function;

// 输出信号
wire tdc_start;
wire tdc_reset;

//==============================================================================
// 被测模块实例化
//==============================================================================
tdc_test_ctrl_phase #(
    .DATA_WIDTH(DATA_WIDTH)
) uut (
    .clk_sys(clk_sys),
    .vio_reset_in(vio_reset_in),
    .vio_phase(vio_phase),
    .vio_valid(vio_valid),
    .sel_function(sel_function),
    .tdc_start(tdc_start),
    .tdc_reset(tdc_reset)
);

//==============================================================================
// 时钟生成 - 200MHz
//==============================================================================
initial begin
    clk_sys = 0;
    forever #(CLK_PERIOD/2) clk_sys = ~clk_sys;
end

//==============================================================================
// 测试任务
//==============================================================================

// 任务：发送单次测量命令
task send_single_shot;
    input [7:0] phase_value;
    begin
        $display("[%0t] 发送单次测量命令: phase=%0d", $time, phase_value);
        vio_phase = phase_value;
        sel_function = 0;  // 单次模式
        vio_valid = 1;
        repeat(10) @(posedge clk_sys);  // 保持 10 个时钟周期 (50ns)
        vio_valid = 0;
        @(posedge clk_sys);
    end
endtask

// 任务：启动扫描模式
task start_scan_mode;
    begin
        $display("[%0t] 启动扫描模式", $time);
        sel_function = 1;  // 扫描模式
        vio_valid = 1;
        repeat(10) @(posedge clk_sys);  // 保持 10 个时钟周期 (50ns)
        vio_valid = 0;
    end
endtask

// 任务：复位
task apply_reset;
    input integer duration;
    begin
        $display("[%0t] 应用复位信号 (%0d ns)", $time, duration);
        vio_reset_in = 1;
        #duration;
        vio_reset_in = 0;
    end
endtask

//==============================================================================
// 监控输出信号
//==============================================================================
always @(posedge tdc_start) begin
    $display("[%0t] ★ TDC_START 脉冲产生", $time);
end

always @(posedge tdc_reset) begin
    $display("[%0t] ⚠ TDC_RESET 脉冲产生", $time);
end

//==============================================================================
// 测试激励
//==============================================================================
initial begin
    // 初始化信号
    vio_reset_in = 0;
    vio_phase = 0;
    vio_valid = 0;
    sel_function = 0;
    
    $display("========================================");
    $display("  TDC Test Control Phase 仿真测试");
    $display("========================================\n");
    
    // 等待几个时钟周期
    repeat(10) @(posedge clk_sys);
    
    // //==========================================================================
    // // 测试1: 单次模式 - 不同相位值
    // //==========================================================================
    // $display("\n【测试1】单次模式测试");
    // $display("------------------------------------------");
    
    // send_single_shot(8'd0);
    // #2000;  // 等待脉冲完成
    
    // send_single_shot(8'd50);
    // #2000;
    
    // send_single_shot(8'd100);
    // #2000;
    
    // send_single_shot(8'd140);
    // #2000;
    
    //==========================================================================
    // 测试2: 扫描模式（观察前几个相位）
    //==========================================================================
    $display("\n【测试2】扫描模式测试");
    $display("------------------------------------------");
    apply_reset(100);
    #2000;
    start_scan_mode();
    #30000;  // 运行一段时间观察扫描过程
    
    // //==========================================================================
    // // 测试3: 复位测试
    // //==========================================================================
    // $display("\n【测试3】复位测试");
    // $display("------------------------------------------");
    
    // apply_reset(100);
    // #2000;
    
    // // 复位后再次单次测试
    // send_single_shot(8'd30);
    // #2000;
    
    // //==========================================================================
    // // 测试4: 快速连续命令
    // //==========================================================================
    // $display("\n【测试4】快速连续命令测试");
    // $display("------------------------------------------");
    
    // send_single_shot(8'd10);
    // #50;  // 缩短等待时间
    // send_single_shot(8'd20);
    // #50;
    // send_single_shot(8'd30);
    // #200;
    
    //==========================================================================
    // 结束仿真
    //==========================================================================
    $display("\n========================================");
    $display("  仿真完成");
    $display("========================================\n");
    
    #5000;
    $finish;
end

